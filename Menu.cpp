// ฟังก์ชันแสดงหน้า Lobby (เมนูหลัก)
bool Menu::showLobby() {
    system("cls");
    std::cout << "=========================================================\n";
    std::cout << "     FIBO SECURITY MANAGEMENT : APPLICATION TERMINAL     \n";
    std::cout << "=========================================================\n\n";
    std::cout << " [1] ยื่นแบบฟอร์มขอเข้าปฏิบัติงานกะดึก\n";
    std::cout << " [2] ยกเลิกคำร้อง และเข้าถึงคลังเอกสารขององค์กร\n\n";
    std::cout << "=========================================================\n";
    std::cout << "ระบุคำสั่ง (1-2): ";

    while (true) {
        if (_kbhit()) {
            char ch = _getch();
            if (ch == '1') {
                std::cout << ch << "\n\n>> กำลังดึงข้อมูลแบบฟอร์มใบสมัคร..." << std::endl;
                Sleep(800);
                return true;
            }
            if (ch == '2') {
                std::cout << ch << "\n\n>> ยกเลิกการทำรายการ กำลังเปิดคลังเอกสาร..." << std::endl;
                Sleep(800);
                return false;
            }
        }
    }
}

// ฟังก์ชันกรอกใบสมัคร + เซ็ตความยากไปในตัว
GameConfig Menu::fillApplication() {
    GameConfig config;
    system("cls");

    std::cout << "=========================================================\n";
    std::cout << "           แบบฟอร์มประเมินและขึ้นทะเบียนพนักงานใหม่           \n";
    std::cout << "=========================================================\n\n";
    
    // ---------------------------------------------------------
    // ข้อ 1: เช็คโรคหัวใจ (ตาม Flowchart บังคับ)
    // ---------------------------------------------------------
    std::cout << " [คำถามที่ 1] คุณมีประวัติโรคหัวใจ หรือมีภาวะอ่อนไหวต่อ\n";
    std::cout << "            สภาพแวดล้อมที่เปลี่ยนแปลงกะทันหันหรือไม่?\n";
    std::cout << "            (Y = มีความเสี่ยง / N = ไม่มีประวัติ): ";
    
    while (true) {
        if (_kbhit()) {
            char ch = toupper(_getch());
            if (ch == 'N') {
                config.enableJumpscare = true;
                std::cout << ch << "\n -> บันทึกผล: สภาพร่างกายผ่านเกณฑ์การเฝ้าระวัง\n\n";
                Sleep(800);
                break;
            } else if (ch == 'Y') {
                config.enableJumpscare = false;
                std::cout << ch << "\n -> บันทึกผล: ไม่ผ่านเกณฑ์ด้านสุขภาพสำหรับการปฏิบัติงานกะดึก\n\n";
                Sleep(800);
                return config; 
            }
        }
    }

    // ---------------------------------------------------------
    // ข้อ 2: เซ็ตความยาก (ซ่อนในรูปแบบ ฐานเงินเดือน และ ความเสี่ยง)
    // ---------------------------------------------------------
    std::cout << " [คำถามที่ 2] โปรดเลือกอัตราค่าตอบแทนตามระดับความเสี่ยงของงานที่คุณประสงค์จะรับผิดชอบ:\n";
    
    std::cout << "   [1] อัตราค่าจ้าง 15,000 บาท/เดือน\n";
    std::cout << "       (ระดับความเสี่ยงต่ำ: ทรัพยากรสนับสนุนเพียงพอ โอกาสเกิดเหตุฉุกเฉินน้อย อัตราการรอดพ้นข้อผิดพลาดสูง)\n\n";
    
    std::cout << "   [2] อัตราค่าจ้าง 25,000 บาท/เดือน\n";
    std::cout << "       (ระดับความเสี่ยงมาตรฐาน: ทรัพยากรมีจำกัด โอกาสเกิดเหตุฉุกเฉินระดับปกติ อนุโลมความผิดพลาดได้ตามเกณฑ์)\n\n";
    
    std::cout << "   [3] อัตราค่าจ้าง 45,000 บาท/เดือน + สวัสดิการค่าเสี่ยงภัย\n";
    std::cout << "       (ระดับความเสี่ยงวิกฤต: ทรัพยากรสนับสนุนต่ำมาก โอกาสเกิดเหตุฉุกเฉินสูงลิ่ว ไม่อนุโลมให้เกิดความผิดพลาด)\n\n";
    
    std::cout << " ระบุตัวเลือกข้อตกลง (1-3): ";
    
    while (true) {
        if (_kbhit()) {
            char ch = _getch();
            if (ch == '1') {
                std::cout << ch << "\n\n -> บันทึกผล: ยอมรับข้อตกลงอัตราค่าจ้าง 15,000 บาท (ระดับความเสี่ยงต่ำ)\n";
                config.maxEnergy = 18;
                config.anomalySpawnChance = 25; 
                config.jumpscareThreshold = 4;
                break;
            } else if (ch == '2') {
                std::cout << ch << "\n\n -> บันทึกผล: ยอมรับข้อตกลงอัตราค่าจ้าง 25,000 บาท (ระดับความเสี่ยงมาตรฐาน)\n";
                config.maxEnergy = 15;
                config.anomalySpawnChance = 35; 
                config.jumpscareThreshold = 3;
                break;
            } else if (ch == '3') {
                std::cout << ch << "\n\n -> บันทึกผล: ยอมรับข้อตกลงอัตราค่าจ้าง 45,000 บาท (ระดับความเสี่ยงวิกฤต)\n";
                config.maxEnergy = 12;
                config.anomalySpawnChance = 45; 
                config.jumpscareThreshold = 2;
                break;
            }
        }
    }

    Sleep(1000);
    std::cout << "\n=========================================================\n";
    std::cout << " >> ระบบบันทึกข้อมูลใบสมัครของคุณเรียบร้อยแล้ว กำลังจัดเตรียมพื้นที่เฝ้าระวัง...\n";
    std::cout << "=========================================================\n";
    Sleep(1500);

    return config;
}